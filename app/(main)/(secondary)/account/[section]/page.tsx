const PAGES = {
  "customer-support": { title: "Help", intro: "Answers to the questions people ask most.", entries: HELP },
  terms: { title: "Terms", intro: "The short version of how Pitchside works.", entries: TERMS },
} as const;

type Props = {
  params: Promise<{ section: string }>;
};

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const { section } = await params;
  const page = PAGES[section as keyof typeof PAGES];
  return { title: page?.title ?? "Account" };
}

export default async function AccountSectionPage({ params }: Props) {
  const { section } = await params;

  if (section === "personal-details") {
    return <PersonalDetailsPageView />;
  }

  if (section === "self-exclusion") {
    return <AccountRestrictionPageView mode="self-exclusion" />;
  }

  if (section === "deactivation") {
    return <AccountRestrictionPageView mode="deactivation" />;
  }

  const page = PAGES[section as keyof typeof PAGES];
  if (!page) notFound();

  return (
    <div className="space-y-4 px-4 py-5 pb-10">
      <header>
        <h1 className="font-heading text-3xl font-extrabold text-[var(--ink)]">{page.title}</h1>
        <p className="mt-1 text-sm text-[var(--ink-3)]">{page.intro}</p>
      </header>
      <dl className="divide-y divide-[var(--ink)]/8 rounded-2xl bg-[var(--paper)] px-4">
        {page.entries.map((entry) => (
          <div key={entry.q} className="py-4">
            <dt className="font-semibold text-[var(--ink)]">{entry.q}</dt>
            <dd className="mt-1 text-sm leading-6 text-[var(--ink-3)]">{entry.a}</dd>
          </div>
        ))}
      </dl>
      {section === "customer-support" ? (
        <Link href="/account/terms" className="inline-block px-1 text-sm font-semibold text-[var(--pitch)]">
          Read the terms
        </Link>
      ) : null}
    </div>
  );
}
